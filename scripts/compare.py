"""Paper-reported vs re-run baselines, side by side.

    uv run python scripts/compare.py

Inputs (whichever exist):
  results/paper_reported.csv     numbers from the JTH README / paper (Tables 7.1-7.2)
  results/upstream/results.csv   official code re-run (scripts/run_upstream.sh)
  results/baselines_upstream.csv our code on the official split
  results/baselines_test.csv     our code on our day-boundary split
Writes results/comparison.md.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from jth.data import ROOT

RES = ROOT / "results"
METRICS = ["MRR", "NDCG@10", "R@10"]

# upstream prediction-file prefix / our model name -> paper row
UPSTREAM_NAMES = {
    "random": "Random", "popularity": "Popularity", "poprecency": "Pop. + recency",
    "pasttemporal": "Past temporal", "cf": "User-based CF", "cfrecency": "CF + recency",
    "jaccard": "Jaccard", "logreg": "Logistic reg.",
}
OUR_NAMES = {
    "Random": "Random", "MostPop": "Popularity", "PopRecency": "Pop. + recency",
    "Recency": "Past temporal", "ItemKNN": "User-based CF", "ContentTFIDF": "Jaccard",
}


def load_upstream(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df["baseline"] = df["file"].map(lambda f: UPSTREAM_NAMES[Path(f).name.split("_")[0]])
    df = df.rename(columns={"mrr": "MRR", "Recall@10": "R@10"})
    return df[["mode", "baseline"] + METRICS]


def load_ours(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df = df[df["group"] == "all"].copy()
    df["baseline"] = df["model"].map(OUR_NAMES)
    return df[["mode", "baseline"] + METRICS]


def main() -> None:
    sources = {
        "paper": (RES / "paper_reported.csv", lambda p: pd.read_csv(p)),
        "official code": (RES / "upstream" / "results.csv", load_upstream),
        "ours, official split": (RES / "baselines_upstream.csv", load_ours),
        "ours, day split": (RES / "baselines_test.csv", load_ours),
    }
    frames = []
    for label, (path, loader) in sources.items():
        if path.exists():
            frames.append(loader(path).assign(source=label))
        else:
            print("missing (skipped):", path.relative_to(ROOT))
    long = pd.concat(frames).melt(id_vars=["mode", "baseline", "source"], var_name="metric")
    order = list(dict.fromkeys(pd.read_csv(RES / "paper_reported.csv")["baseline"]))

    lines = ["# Baselines: paper vs re-runs", "",
             "Generated by `scripts/compare.py`. Our models map to the closest paper row: "
             "MostPop = Popularity, Recency = Past temporal, ItemKNN = User-based CF, "
             "ContentTFIDF ~ Jaccard (TF-IDF cosine instead of Jaccard, same fields).", ""]
    for mode in ("c2j", "j2c"):
        for metric in METRICS:
            sub = long[(long["mode"] == mode) & (long["metric"] == metric)]
            if sub.empty:
                continue
            table = sub.pivot_table(index="baseline", columns="source", values="value", aggfunc="first")
            table = table.reindex([b for b in order if b in table.index])
            table = table[[s for s in sources if s in table.columns]]
            lines += [f"## {mode} - {metric}", "", "| baseline | " + " | ".join(table.columns) + " |",
                      "|---|" + "---|" * len(table.columns)]
            for name, row in table.iterrows():
                cells = ["" if pd.isna(v) else f"{v:.3f}" for v in row]
                lines.append(f"| {name} | " + " | ".join(cells) + " |")
            lines.append("")
    (RES / "comparison.md").write_text("\n".join(lines))
    print("comparison ->", RES / "comparison.md")


if __name__ == "__main__":
    main()
